#!/usr/bin/env python3
"""Hash-pinned Python requirements for the native desktop builds, one file per platform.

requirements-build.txt, with the requirements-runtime.txt it includes, names
the exact versions the desktop packages freeze. The native build and signing
jobs install from packaging/native-requirements/<platform>.txt instead: the
same pins, plus every package they pull in on that platform, each with the
SHA-256 of every wheel PyPI publishes for that platform and CPython 3.11 to
3.14. pip then installs them with --require-hashes --only-binary=:all: and
refuses any other bytes, and the project itself installs with --no-deps
--no-build-isolation --no-index, so nothing else is fetched:

    python -m pip install --require-hashes --only-binary=:all: \\
        -r packaging/native-requirements/linux-x86_64.txt
    python -m pip install --no-deps --no-build-isolation --no-index -e .

    python tools/native_requirements.py check   # offline; the tests run it
    python tools/native_requirements.py lock    # after editing the pins

`lock` resolves each platform with uv and reads the wheel digests from PyPI's
JSON API, so it needs uv and the network. `check` needs neither: it requires
every platform file to carry the current pins and a digest of the pin files it
was generated from, so an edited pin fails until the files are regenerated.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

try:
    from tools import download_retry
except ModuleNotFoundError:  # `python tools/native_requirements.py`
    import download_retry

ROOT = Path(__file__).resolve().parents[1]
PINS = ROOT / "requirements-build.txt"
OUTPUT = ROOT / "packaging" / "native-requirements"
PYTHONS = ("3.11", "3.12", "3.13", "3.14")
# uv's --python-platform name, and the wheel platform tags each build host accepts.
PLATFORMS = {
    "linux-x86_64": ("x86_64-unknown-linux-gnu", re.compile(r"manylinux[0-9_]*_x86_64")),
    "windows-x86_64": ("x86_64-pc-windows-msvc", re.compile(r"win_amd64")),
    "macos-arm64": (
        "aarch64-apple-darwin",
        re.compile(r"macosx_[0-9]+_[0-9]+_(?:arm64|universal2)"),
    ),
}
HEADER = "# Generated by tools/native_requirements.py lock; do not edit."
INPUTS = re.compile(r"# inputs sha256: ([0-9a-f]{64})")
PIN = re.compile(r"([A-Za-z0-9][A-Za-z0-9._-]*)==([A-Za-z0-9][A-Za-z0-9.+!_-]*)")
HASH = re.compile(r"--hash=sha256:([0-9a-f]{64})")


class LockError(ValueError):
    """A requirement file that does not match the pins or is not hash-complete."""


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def input_files(path: Path = PINS) -> list[Path]:
    """requirements-build.txt and every file it includes with -r, in order."""
    files = [path]
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("-r "):
            files += input_files(path.parent / line[3:].strip())
    return files


def pins(path: Path = PINS) -> dict[str, str]:
    """The exact name==version pins of the human-edited pin files."""
    found: dict[str, str] = {}
    for file in input_files(path):
        for raw in file.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line or line.startswith("-r "):
                continue
            match = PIN.fullmatch(line)
            if not match:
                raise LockError(f"{file.name}: not an exact pin: {raw!r}")
            name = normalize(match.group(1))
            if name in found and found[name] != match.group(2):
                raise LockError(f"{name} is pinned twice with different versions")
            found[name] = match.group(2)
    return found


def inputs_digest(path: Path = PINS) -> str:
    digest = hashlib.sha256()
    for file in input_files(path):
        digest.update(file.relative_to(path.parent).as_posix().encode() + b"\0")
        digest.update(file.read_bytes() + b"\0")
    return digest.hexdigest()


def logical_lines(text: str) -> list[str]:
    """Requirement lines with their backslash continuations joined, comments dropped."""
    lines: list[str] = []
    for raw in text.splitlines():
        if raw.startswith("#") or not raw.strip():
            continue
        if lines and lines[-1].endswith("\\"):
            lines[-1] = lines[-1][:-1] + " " + raw.strip()
        else:
            lines.append(raw.strip())
    return lines


def parse(text: str) -> tuple[str | None, dict[str, tuple[str, list[str]]]]:
    """Return (recorded inputs digest, {name: (version, hashes)}) of a platform file."""
    recorded = next(
        (match.group(1) for line in text.splitlines() if (match := INPUTS.fullmatch(line))),
        None,
    )
    requirements: dict[str, tuple[str, list[str]]] = {}
    for line in logical_lines(text):
        requirement, *options = line.split()
        match = PIN.fullmatch(requirement)
        if not match or line.endswith("\\"):
            raise LockError(f"Not an exact, complete pin: {line!r}")
        hashes = [found.group(1) for option in options if (found := HASH.fullmatch(option))]
        if len(hashes) != len(options):
            raise LockError(f"Only --hash=sha256 options may follow a pin: {line!r}")
        name = normalize(match.group(1))
        if not hashes:
            raise LockError(f"{name} has no hash")
        if name in requirements:
            raise LockError(f"{name} is listed twice")
        requirements[name] = (match.group(2), hashes)
    return recorded, requirements


def check(output: Path = OUTPUT, path: Path = PINS) -> dict[str, int]:
    """Require every platform file to be hash-complete and generated from the current pins."""
    expected = pins(path)
    digest = inputs_digest(path)
    versions: dict[str, dict[str, str]] = {}
    counts = {}
    for platform in PLATFORMS:
        file = output / f"{platform}.txt"
        if not file.is_file():
            raise LockError(f"Missing {file.name}; run tools/native_requirements.py lock")
        recorded, requirements = parse(file.read_text(encoding="utf-8"))
        if recorded != digest:
            raise LockError(
                f"{file.name} was generated from other pins; run tools/native_requirements.py lock"
            )
        for name, version in expected.items():
            if name not in requirements:
                raise LockError(f"{file.name} is missing {name}=={version}")
            if requirements[name][0] != version:
                raise LockError(
                    f"{file.name} has {name}=={requirements[name][0]}, the pin is {version}"
                )
        for name, (version, _hashes) in requirements.items():
            versions.setdefault(name, {})[platform] = version
        counts[platform] = len(requirements)
    for name, by_platform in versions.items():
        if len(set(by_platform.values())) > 1:
            raise LockError(f"{name} differs between platforms: {by_platform}")
    return counts


# --- lock (maintainers; uv and the network) ----------------------------------------


def wheel_tags(filename: str) -> list[tuple[str, str, str]]:
    """(interpreter, abi, platform) tags of a wheel filename."""
    parts = filename.removesuffix(".whl").split("-")
    if len(parts) < 5:
        raise LockError(f"Not a wheel filename: {filename}")
    interpreters, abis, platforms = parts[-3:]
    return [
        (interpreter, abi, platform)
        for interpreter in interpreters.split(".")
        for abi in abis.split(".")
        for platform in platforms.split(".")
    ]


def compatible(filename: str, platform: str) -> bool:
    """Whether the wheel installs on this platform under any of PYTHONS."""
    accepts = PLATFORMS[platform][1]
    minors = {int(version.split(".")[1]) for version in PYTHONS}
    for interpreter, abi, tag in wheel_tags(filename):
        if tag != "any" and not accepts.fullmatch(tag):
            continue
        if interpreter in ("py3", "py2") and abi == "none":
            return True
        if not re.fullmatch(r"(?:cp|py)3[0-9]+", interpreter):
            continue
        minor = int(interpreter[3:])
        if abi == "abi3" and interpreter.startswith("cp") and minor <= max(minors):
            return True
        if minor in minors and abi in ("none", f"cp3{minor}"):
            return True
    return False


def resolve(platform: str, path: Path = PINS) -> dict[str, str]:
    """name==version for the platform's complete dependency closure, from uv."""
    target = PLATFORMS[platform][0]
    result = subprocess.run(
        [
            "uv",
            "pip",
            "compile",
            str(path),
            "--python-platform",
            target,
            "--python-version",
            PYTHONS[0],
            "--only-binary",
            ":all:",
            "--no-header",
            "--no-annotate",
            "--quiet",
        ],
        cwd=path.parent,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode:
        raise LockError(f"uv could not resolve {platform}:\n{result.stderr}")
    resolved = {}
    for line in result.stdout.splitlines():
        match = PIN.fullmatch(line.strip())
        if match:
            resolved[normalize(match.group(1))] = match.group(2)
    return resolved


def pypi_wheels(
    name: str, version: str, opener=urllib.request.urlopen, sleep=time.sleep
) -> list[dict]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    request = urllib.request.Request(url, headers={"User-Agent": "platefold-native-requirements"})
    try:
        body = download_retry.read(
            request, name=url, limit=None, timeout=60, opener=opener, sleep=sleep
        )
    except download_retry.Failed as failure:
        raise LockError(f"Download of {url} {failure}: {failure.error}") from None
    release = json.loads(body)
    return [
        {"filename": item["filename"], "sha256": item["digests"]["sha256"]}
        for item in release["urls"]
        if item["packagetype"] == "bdist_wheel" and not item.get("yanked")
    ]


def render(platform: str, digest: str, closure: dict[str, list[str]], versions) -> str:
    lines = [
        HEADER,
        f"# Platform: {platform}, CPython {PYTHONS[0]} to {PYTHONS[-1]}; pins from",
        "# requirements-build.txt. Install with --require-hashes --only-binary=:all:.",
        f"# inputs sha256: {digest}",
    ]
    for name in sorted(closure):
        hashes = sorted(closure[name])
        lines.append(f"{name}=={versions[name]} \\")
        lines += [f"    --hash=sha256:{value} \\" for value in hashes[:-1]]
        lines.append(f"    --hash=sha256:{hashes[-1]}")
    return "\n".join(lines) + "\n"


def lock(output: Path = OUTPUT, path: Path = PINS, fetch=pypi_wheels, resolver=resolve) -> None:
    expected = pins(path)
    digest = inputs_digest(path)
    rendered = {}
    for platform in PLATFORMS:
        versions = resolver(platform, path)
        for name, version in expected.items():
            if versions.get(name) != version:
                raise LockError(f"uv resolved {name}=={versions.get(name)} for {platform}")
        closure = {}
        for name, version in versions.items():
            hashes = [
                wheel["sha256"]
                for wheel in fetch(name, version)
                if compatible(wheel["filename"], platform)
            ]
            if not hashes:
                raise LockError(f"PyPI has no {platform} wheel for {name}=={version}")
            closure[name] = hashes
        rendered[platform] = render(platform, digest, closure, versions)
    output.mkdir(parents=True, exist_ok=True)
    for platform, text in rendered.items():
        (output / f"{platform}.txt").write_text(text, encoding="utf-8")
    check(output, path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("command", choices=("check", "lock"))
    args = parser.parse_args(argv)
    try:
        if args.command == "lock":
            lock()
        counts = check()
    except (LockError, OSError) as error:
        print(error, file=sys.stderr)
        return 1
    for platform, count in counts.items():
        print(f"{platform}: {count} hash-pinned requirements match requirements-build.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
